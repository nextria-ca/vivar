//! `vivar export docker`: a Dockerfile that rebuilds the locked environment.

use crate::project::{Policy, Project};
use anyhow::Result;
use std::fs;

pub fn dockerfile(project: &Project, policy: &Policy) -> Result<String> {
    let python = fs::read_to_string(project.venv_root().join(".python-version"))
        .map(|s| s.trim().to_owned())
        .unwrap_or_else(|_| "3.12".to_owned());
    let mut out = String::new();
    out.push_str("# Generated by vivar export docker. The lockfile is the source of truth:\n");
    out.push_str("# the image installs exactly what uv.lock pins, nothing newer.\n");
    out.push_str(&format!("FROM python:{python}-slim\n"));
    out.push_str("COPY --from=ghcr.io/astral-sh/uv:latest /uv /usr/local/bin/uv\n");
    out.push_str("ENV UV_PYTHON_DOWNLOADS=never UV_LINK_MODE=copy UV_FROZEN=1\n");
    if let Some(index) = &policy.index_url {
        if index.contains("://") {
            out.push_str(&format!("ENV UV_DEFAULT_INDEX={index}\n"));
        }
    }
    out.push_str("WORKDIR /app\n");
    out.push_str("COPY pyproject.toml uv.lock ./\n");
    out.push_str("RUN uv sync --no-dev --no-install-project\n");
    out.push_str("COPY . .\n");
    out.push_str("RUN uv sync --no-dev\n");
    out.push_str("ENV PATH=\"/app/.venv/bin:$PATH\"\n");
    out.push_str("CMD [\"python\"]\n");
    Ok(out)
}
