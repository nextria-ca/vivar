//! `vivar export docker`: a Dockerfile that rebuilds the locked environment.

use crate::lock::Lock;
use crate::project::{Policy, Project};
use anyhow::Result;
use std::fs;

/// The Python series for the base image: the pin, else the floor of
/// `requires-python`, else what the env runs, else 3.12.
fn python_series(project: &Project) -> String {
    let root = project.venv_root();
    let from_pin = fs::read_to_string(root.join(".python-version"))
        .ok()
        .map(|s| s.trim().to_owned())
        .filter(|s| !s.is_empty());
    let from_requires = project.requires_python().and_then(|spec| {
        spec.split(',')
            .map(str::trim)
            .find_map(|c| {
                c.strip_prefix(">=")
                    .or_else(|| c.strip_prefix("~="))
                    .or_else(|| c.strip_prefix("=="))
            })
            .map(|v| v.trim().trim_end_matches(".*").to_owned())
    });
    let from_env = fs::read_to_string(root.join(".venv").join("pyvenv.cfg"))
        .ok()
        .and_then(|cfg| {
            cfg.lines().find_map(|l| {
                l.strip_prefix("version_info")
                    .map(|v| v.trim_start_matches([' ', '=']).trim().to_owned())
            })
        });
    // An exact pin names an exact image tag (python:3.12.4-slim exists); a
    // floor from requires-python or the env only fixes the series.
    match from_pin {
        Some(pin) => pin.split('.').take(3).collect::<Vec<_>>().join("."),
        None => from_requires
            .or(from_env)
            .unwrap_or_else(|| "3.12".to_owned())
            .split('.')
            .take(2)
            .collect::<Vec<_>>()
            .join("."),
    }
}

pub fn dockerfile(project: &Project, policy: &Policy) -> Result<String> {
    let python = python_series(project);
    // Local sources (path deps, workspace members) only exist after `COPY . .`,
    // so the dependency-only layer is skipped when the lock has any.
    let has_local = Lock::read(project.venv_root())
        .map(|lock| {
            lock.packages
                .iter()
                .any(|p| matches!(p.source_kind.as_str(), "editable" | "directory" | "path"))
        })
        .unwrap_or(false);
    let mut out = String::new();
    out.push_str("# Generated by vivar export docker. The lockfile is the source of truth:\n");
    out.push_str("# the image installs exactly what uv.lock pins, nothing newer.\n");
    out.push_str(&format!("FROM python:{python}-slim\n"));
    out.push_str("COPY --from=ghcr.io/astral-sh/uv:latest /uv /usr/local/bin/uv\n");
    out.push_str("ENV UV_PYTHON_DOWNLOADS=never UV_LINK_MODE=copy UV_FROZEN=1\n");
    if let Some(index) = &policy.index_url {
        if index.contains("://") {
            out.push_str(&format!("ENV UV_DEFAULT_INDEX={index}\n"));
        }
    }
    out.push_str("WORKDIR /app\n");
    if !has_local {
        out.push_str("COPY pyproject.toml uv.lock ./\n");
        out.push_str("RUN uv sync --no-dev --no-install-project\n");
    }
    out.push_str("COPY . .\n");
    out.push_str("RUN uv sync --no-dev\n");
    out.push_str("ENV PATH=\"/app/.venv/bin:$PATH\"\n");
    out.push_str("CMD [\"python\"]\n");
    Ok(out)
}
